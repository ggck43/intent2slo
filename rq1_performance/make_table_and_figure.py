"""RQ1 table and figure of the paper (Section IV-A).

Inputs (released analysis results, in results/):
  V-01_f1_real_synthetic_total.csv  strict micro-F1 (Total column)
  V-03_em_and_jaccard.csv           exact match
  V-08_f1_explicit_implicit.csv     F1 on explicit vs grounded (implicit) SLOs
Outputs:
  results/tab2_rq1.tex   Table II (booktabs; best per column bold, second best underlined)
  results/tab2_rq1.csv
  figures/fig2_explicit_grounded.pdf and .png
Run from anywhere: python3 rq1_performance/make_table_and_figure.py
"""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
OUT_T = RES
OUT_F = HERE / "figures"
OUT_F.mkdir(exist_ok=True)

MODELS = [  # (family, csv name, paper name), grouped by family, small then large
    ("Qwen3.5", "Qwen3.5-4B", "Qwen3.5-4B"), ("Qwen3.5", "Qwen3.5-9B", "Qwen3.5-9B"),
    ("Gemma 4", "Gemma4-E2B", "Gemma-4-E2B"), ("Gemma 4", "Gemma4-E4B", "Gemma-4-E4B"),
    ("Ministral 3", "Ministral-3-3B", "Ministral-3-3B"), ("Ministral 3", "Ministral-3-8B", "Ministral-3-8B"),
    ("Granite 4.1", "Granite-4.1-3B", "Granite-4.1-3B"), ("Granite 4.1", "Granite-4.1-8B", "Granite-4.1-8B"),
    ("Llama 3", "Llama-3.2-3B", "Llama-3.2-3B"), ("Llama 3", "Llama-3.1-8B", "Llama-3.1-8B"),
]
SETUPS = [("ZS", "zs"), ("FS", "fs"), ("ZS-CoT", "zs-cot"), ("FS-CoT", "fs-cot")]

f1 = pd.read_csv(RES / "V-01_f1_real_synthetic_total.csv").pivot(index="model", columns="method", values="Total")
em = pd.read_csv(RES / "V-03_em_and_jaccard.csv").pivot(index="model", columns="method", values="Exact match")

rows = []
for fam, key, name in MODELS:
    r = {"family": fam, "model": name}
    for m, s in SETUPS:
        r[f"{s} F1"] = round(f1.loc[key, m], 3)
        r[f"{s} EM"] = round(em.loc[key, m], 3)
    r["mean F1"] = round(sum(f1.loc[key, m] for m, _ in SETUPS) / 4, 3)
    rows.append(r)
tab = pd.DataFrame(rows)
cols = [c for c in tab.columns if c not in ("family", "model")]


def mark(col):
    """Bold the best and underline the second-best value of a column (ties share the mark)."""
    vals = sorted(set(tab[col]), reverse=True)
    best, second = vals[0], vals[1]
    out = []
    for v in tab[col]:
        s = f"{v:.3f}"
        out.append(r"\textbf{" + s + "}" if v == best else (r"\underline{" + s + "}" if v == second else s))
    return out


marked = {c: mark(c) for c in cols}
lines = [
    r"\begin{tabular}{ll" + "cc" * 4 + "c}",
    r"\toprule",
    r" & & \multicolumn{2}{c}{\texttt{zs}} & \multicolumn{2}{c}{\texttt{fs}} & \multicolumn{2}{c}{\texttt{zs-cot}} & \multicolumn{2}{c}{\texttt{fs-cot}} & Mean \\",
    r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}",
    r"Family & Size & $F_1$ & EM & $F_1$ & EM & $F_1$ & EM & $F_1$ & EM & $F_1$ \\",
    r"\midrule",
]
for i, r in tab.iterrows():
    fam = r["family"] if i % 2 == 0 else ""
    cells = " & ".join(marked[c][i] for c in cols)
    size = r["model"].split("-")[-1]  # e.g. Qwen3.5-4B -> 4B, Gemma-4-E2B -> E2B
    lines.append(f"{fam} & {size} & {cells} \\\\")
    if i % 2 == 1 and i < len(tab) - 1:
        lines.append(r"\addlinespace[2pt]")
lines += [r"\bottomrule", r"\end{tabular}"]
(OUT_T / "tab2_rq1.tex").write_text(
    "% Generated by rq1_performance/make_table_and_figure.py from V-01 (F1 Total) and V-03 (exact match); do not edit by hand.\n"
    + "\n".join(lines) + "\n")
tab.to_csv(OUT_T / "tab2_rq1.csv", index=False)

# ---- Fig. 2: explicit vs grounded vs overall F1, fs-cot, Qwen and Gemma ----
ex = pd.read_csv(RES / "V-08_f1_explicit_implicit.csv")
ex = ex[ex.prompt == "fs3 CoT"].set_index("model")
fig_models = [("Qwen3.5-4B", "Qwen3.5\n4B"), ("Qwen3.5-9B", "Qwen3.5\n9B"),
              ("Gemma4-E2B", "Gemma-4\nE2B"), ("Gemma4-E4B", "Gemma-4\nE4B")]
series = [  # (label, values, colour, hatch); colours validated (CVD and normal-vision separation pass)
    ("Explicit SLOs", [ex.loc[k, "explicit"] for k, _ in fig_models], "#2a78d6", ""),
    ("Implicit SLOs", [ex.loc[k, "implicit"] for k, _ in fig_models], "#eb6834", "///"),
    ("All SLOs", [f1.loc[k, "FS-CoT"] for k, _ in fig_models], "#1baf7a", ".."),
]
plt.rcParams.update({"font.family": "serif", "font.size": 7, "hatch.linewidth": 0.5})
fig, ax = plt.subplots(figsize=(3.45, 1.85))
w = 0.26
for j, (lab, vals, col, hatch) in enumerate(series):
    xs = [i + (j - 1) * (w + 0.02) for i in range(len(fig_models))]
    bars = ax.bar(xs, vals, w, label=lab, color=col, hatch=hatch, edgecolor="white", linewidth=0.6)
    for x, v in zip(xs, vals):
        ax.text(x, v + 0.012, f"{v:.2f}", ha="center", va="bottom", fontsize=5.6, color="#333333")
ax.set_xticks(range(len(fig_models)))
ax.set_xticklabels([n for _, n in fig_models])
ax.set_ylabel(r"Strict micro-$F_1$")
ax.set_ylim(0, 1.12)
ax.set_yticks([0, 0.25, 0.5, 0.75, 1.0])
ax.grid(axis="y", color="#dddddd", linewidth=0.5)
ax.set_axisbelow(True)
for s in ("top", "right"):
    ax.spines[s].set_visible(False)
ax.legend(ncol=3, loc="upper center", bbox_to_anchor=(0.5, 1.13), frameon=False, fontsize=6.5,
          handlelength=1.4, columnspacing=1.0)
fig.tight_layout(pad=0.2)
fig.savefig(OUT_F / "fig2_explicit_grounded.pdf")
fig.savefig(OUT_F / "fig2_explicit_grounded.png", dpi=200)
print(tab.to_string())
print(ex.loc[[k for k, _ in fig_models], ["explicit", "implicit"]].round(3))
